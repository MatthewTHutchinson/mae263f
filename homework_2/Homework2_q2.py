def run_simulation(P, nv=50, totalTime=1.0, dt=0.001):
    """
    Runs the dynamic beam simulation for a given point load P.

    Parameters
    ----------
    P : float
        Applied point load (N)
    nv : int, optional
        Number of nodes (default 50)
    totalTime : float, optional
        Total simulation time (s)
    dt : float, optional
        Time step size (s)

    Returns
    -------
    y_max_ss : float
        Steady-state maximum vertical displacement (m)
    """
    # -------------------------------------------------
    # Initialization and Geometry
    ndof = 2 * nv
    midNode = nv // 2
    RodLength = 1.0
    deltaL = RodLength / (nv - 1)
    l = RodLength

    # Material properties
    rho_metal = 2700  # kg/m^3
    Y = 70e9          # Pa
    r0 = 0.011
    R = 0.013
    A = np.pi * (R**2 - r0**2)
    I = (np.pi / 4) * (R**4 - r0**4)
    EA = Y * A
    EI = Y * I

    # Mass matrix
    m_node = A * l * rho_metal / (nv - 1)
    m = m_node * np.ones(2 * nv)
    mMat = np.diag(m)

    # Damping (none for HW2)
    C = np.zeros((2 * nv, 2 * nv))

    # Tolerance
    tol = EI / RodLength ** 2 * 1e-3
    maximum_iter = 1000

    # Node coordinates
    nodes = np.zeros((nv, 2))
    for c in range(nv):
        nodes[c, 0] = c * deltaL
        nodes[c, 1] = 0.0

    # Initial positions and velocities
    q0 = np.zeros(2 * nv)
    for c in range(nv):
        q0[2 * c] = nodes[c, 0]
        q0[2 * c + 1] = nodes[c, 1]
    u0 = np.zeros(2 * nv)

    # -------------------------------------------------
    # Point Load setup
    d = 0.75  # m from left
    x_coords = np.linspace(0, l, nv)
    load_node = np.argmin(np.abs(x_coords - d))
    W = np.zeros(2 * nv)
    W[2 * load_node + 1] = -P  # downward force

    # -------------------------------------------------
    # Boundary conditions
    all_DOFs = np.arange(ndof)
    fixed_index = np.array([0, 1, 2 * nv - 1])  # pin & roller
    free_index = np.setdiff1d(all_DOFs, fixed_index)

    # -------------------------------------------------
    # Time stepping
    Nsteps = round(totalTime / dt)
    y_max_over_time = np.zeros(Nsteps)

    q_new = q0.copy()
    u_new = u0.copy()

    for timeStep in range(1, Nsteps):
        q_new, error = objfun(q0, u0, dt, tol, maximum_iter, m, mMat, EI, EA, W, C, deltaL, free_index)
        if error < 0:
            print(f"Convergence failed at step {timeStep} for P = {P} N.")
            break

        u_new = (q_new - q0) / dt
        y_positions = q_new[1::2]  # all y DOFs
        y_max_over_time[timeStep] = np.min(y_positions)  # most negative y

        q0 = q_new.copy()
        u0 = u_new.copy()

    # -------------------------------------------------
    # Steady-state displacement (average last 10% of steps)
    steady_window = int(0.1 * Nsteps)
    y_max_ss = np.mean(y_max_over_time[-steady_window:])

    return y_max_ss

